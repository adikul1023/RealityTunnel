"""
jwt_service.py — JWT Engine for RealityTunnel Billing/Auth Access Tokens.

SECURITY & ARCHITECTURAL DECISIONS:
1. Why Ed25519 (EdDSA) instead of HS256:
   Asymmetric Ed25519 cryptography cleanly separates identity issuance from token verification. The Billing/Auth server
   retains the private signing key to issue signed access tokens. Future middleware, VPN servers, or client APIs only
   need the public key to verify tokens without ever possessing the secret required to forge tokens. This avoids the
   security hazards of shared-secret HMACs (HS256) across distributed systems. Furthermore, Ed25519 signatures are
   exceptionally fast, produce compact 64-byte signatures, and are immune to RSA padding and key-confusion attacks.

2. Why minimal claims:
   Tokens include only `sub` (Account UUID), `account` (Account ID), `device` (Device GUID), and standard RFC 7519
   registered claims (`iss`, `aud`, `iat`, `nbf`, `exp`, `jti`). We omit Master Tokens, hashes, emails, roles, and
   subscription details to prevent data leaks if tokens are logged by client telemetry or captured in transit.

3. Why 15-minute lifetime (`ACCESS_TOKEN_EXPIRE_MINUTES = 15`):
   Access tokens are stateless bearer credentials. A brief 15-minute window minimizes the impact of token interception.
   Long-term sessions are sustained via Refresh Token Rotation (Phase 1.3.4), avoiding database lookups on every API request.

4. Why JWT includes a unique `jti` claim:
   A cryptographically random 128-bit hex string identifies each token uniquely. This enables future capabilities such as
   replay attack detection, audit logging, and rapid short-term blocklisting without altering token structure.

5. Why verification validates Issuer (`iss`) and Audience (`aud`):
   Validating `iss` ("RealityTunnel Billing/Auth") and `aud` ("RealityTunnel Client") prevents cross-service token
   substitution attacks, ensuring tokens intended for one client or generated by another issuer cannot be misused here.

KEY MANAGEMENT APPROACH:
- Development mode: If Ed25519 PEM keys are absent from the configured key directory, they are automatically generated and
  saved with restrictive file permissions (0600).
- Production mode: Auto-generation is strictly prohibited. The service raises a RuntimeError if keys are not securely
  pre-provisioned.
"""
from __future__ import annotations

import logging
import os
import secrets
import stat
import uuid
from datetime import datetime, timezone, timedelta
from pathlib import Path
from typing import Any

import jwt
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ed25519

from app.security.jwt_models import (
    AccessTokenClaims,
    ACCESS_TOKEN_EXPIRE_MINUTES,
    JWT_ALGORITHM,
    JWT_AUDIENCE,
    JWT_ISSUER,
)
from app.services.exceptions import (
    InvalidAudienceError,
    InvalidIssuerError,
    InvalidSignatureError,
    InvalidTokenError,
    TokenExpiredError,
    TokenNotYetValidError,
)

logger = logging.getLogger(__name__)


class JWTService:
    """
    Dedicated engine for issuing and verifying Ed25519 signed Access JWTs.
    Strictly independent of FastAPI routes, login endpoints, refresh tokens, and HTTP middleware.
    """

    def __init__(
        self,
        keys_dir: Path | str | None = None,
        environment: str | None = None,
    ) -> None:
        if environment is None:
            from app.config import settings
            self.environment = settings.environment
        else:
            self.environment = environment

        if keys_dir is None:
            # Default to dev_keys directory in project root
            self.keys_dir = Path(__file__).resolve().parent.parent.parent / "dev_keys"
        else:
            self.keys_dir = Path(keys_dir)

        self.private_key: ed25519.Ed25519PrivateKey | None = None
        self.public_key: ed25519.Ed25519PublicKey | None = None

        self._load_or_generate_keys()

    def _load_or_generate_keys(self) -> None:
        """Load Ed25519 keys from disk or auto-generate them if in development mode."""
        private_key_path = self.keys_dir / "ed25519_private.pem"
        public_key_path = self.keys_dir / "ed25519_public.pem"

        if private_key_path.exists() and public_key_path.exists():
            private_bytes = private_key_path.read_bytes()
            public_bytes = public_key_path.read_bytes()
            self.private_key = serialization.load_pem_private_key(private_bytes, password=None)  # type: ignore
            self.public_key = serialization.load_pem_public_key(public_bytes)  # type: ignore
            return

        if self.environment.lower() == "production":
            raise RuntimeError(
                "Production Ed25519 signing keys are absent from disk! "
                "Automatic key generation is strictly prohibited in production environments."
            )

        # Development / test auto-generation
        self.keys_dir.mkdir(parents=True, exist_ok=True)
        new_private = ed25519.Ed25519PrivateKey.generate()
        new_public = new_private.public_key()

        private_pem = new_private.private_bytes(
            encoding=serialization.Encoding.PEM,
            format=serialization.PrivateFormat.PKCS8,
            encryption_algorithm=serialization.NoEncryption(),
        )
        public_pem = new_public.public_bytes(
            encoding=serialization.Encoding.PEM,
            format=serialization.PublicFormat.SubjectPublicKeyInfo,
        )

        private_key_path.write_bytes(private_pem)
        public_key_path.write_bytes(public_pem)

        # Apply restrictive permissions on Unix systems
        try:
            os.chmod(private_key_path, stat.S_IRUSR | stat.S_IWUSR)
            os.chmod(public_key_path, stat.S_IRUSR | stat.S_IWUSR | stat.S_IRGRP | stat.S_IROTH)
        except Exception:
            pass

        self.private_key = new_private
        self.public_key = new_public

    def issue_access_token(
        self,
        account_uuid: str | uuid.UUID,
        account_id: str,
        device_guid: str,
    ) -> str:
        """
        Issue a new 15-minute stateless Access JWT signed with Ed25519.

        LOGGING INVARIANT: Never logs token strings or private keys.
        """
        if self.private_key is None:
            raise RuntimeError("Private signing key is not initialized.")

        now = datetime.now(timezone.utc)
        iat = int(now.timestamp())
        nbf = iat
        exp = int((now + timedelta(minutes=ACCESS_TOKEN_EXPIRE_MINUTES)).timestamp())
        jti = secrets.token_hex(16)

        payload = {
            "sub": str(account_uuid),
            "account": str(account_id),
            "device": str(device_guid),
            "iss": JWT_ISSUER,
            "aud": JWT_AUDIENCE,
            "iat": iat,
            "nbf": nbf,
            "exp": exp,
            "jti": jti,
        }

        token = jwt.encode(payload, self.private_key, algorithm=JWT_ALGORITHM)
        logger.info("Access token issued")
        return token

    def verify_access_token(self, token: str) -> AccessTokenClaims:
        """
        Verify an Access JWT signature, expiration, issuer, audience, and required claims.
        Returns typed AccessTokenClaims or raises dedicated JWT service exceptions.

        LOGGING INVARIANT: Never logs token strings, public keys, or decoded claim contents.
        """
        if self.public_key is None:
            raise RuntimeError("Public verification key is not initialized.")

        try:
            payload = jwt.decode(
                token,
                self.public_key,
                algorithms=[JWT_ALGORITHM],
                issuer=JWT_ISSUER,
                audience=JWT_AUDIENCE,
                leeway=0,  # Explicitly disallow clock skew for stateless access tokens
                options={
                    "require": ["sub", "account", "device", "iss", "aud", "iat", "nbf", "exp", "jti"],
                    "verify_signature": True,
                    "verify_exp": True,
                    "verify_nbf": True,
                    "verify_iat": True,
                    "verify_iss": True,
                    "verify_aud": True,
                },
            )
        except jwt.ExpiredSignatureError as e:
            logger.info("JWT validation failed: Token expired")
            raise TokenExpiredError("Access token has expired", detail=str(e)) from e
        except jwt.ImmatureSignatureError as e:
            logger.info("JWT validation failed: Token not yet valid")
            raise TokenNotYetValidError("Access token is not yet valid (nbf)", detail=str(e)) from e
        except jwt.InvalidSignatureError as e:
            logger.info("JWT validation failed: Invalid signature")
            raise InvalidSignatureError("Access token signature verification failed", detail=str(e)) from e
        except jwt.InvalidIssuerError as e:
            logger.info("JWT validation failed: Invalid issuer")
            raise InvalidIssuerError("Access token issuer verification failed", detail=str(e)) from e
        except jwt.InvalidAudienceError as e:
            logger.info("JWT validation failed: Invalid audience")
            raise InvalidAudienceError("Access token audience verification failed", detail=str(e)) from e
        except jwt.MissingRequiredClaimError as e:
            logger.info("JWT validation failed: Missing required claim")
            raise InvalidTokenError(f"Missing required JWT claim: {str(e)}", detail=str(e)) from e
        except jwt.PyJWTError as e:
            logger.info("JWT validation failed: Invalid token")
            raise InvalidTokenError("Access token is invalid or malformed", detail=str(e)) from e
        except Exception as e:
            logger.info("JWT validation failed: Invalid token")
            raise InvalidTokenError("Unexpected error validating access token", detail=str(e)) from e

        try:
            return AccessTokenClaims.from_dict(payload)
        except ValueError as e:
            logger.info("JWT validation failed: Missing required claim")
            raise InvalidTokenError(str(e), detail=str(e)) from e
