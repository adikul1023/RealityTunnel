"""
refresh_tokens.py — Core Refresh Token Rotation (RTR) Engine.

Pure domain service responsible for issuing, validating, rotating, and revoking long-lived refresh tokens.
Strictly decoupled from HTTP frameworks, FastAPI routing, middleware, and request/response objects.

ARCHITECTURAL DESIGN & SECURITY REASONING:

1. WHY SHA-256 IS SUFFICIENT FOR REFRESH TOKENS:
   Refresh tokens are generated by the server via OS CSPRNG (`secrets.token_hex(32)`), providing 256 bits of
   true high entropy. Unlike human-chosen passwords, a 256-bit CSPRNG secret has 2^256 possible values, making
   offline dictionary attacks, rainbow tables, and brute-force guessing mathematically impossible. Therefore,
   memory-hard Key Derivation Functions (like Argon2id or bcrypt) are unnecessary and would only cause severe
   CPU/RAM exhaustion under high authentication load. Standard SHA-256 hashing provides optimal verification
   speed and collision resistance.

2. WHY REFRESH TOKENS ARE ROTATED:
   Session rotation minimizes the window of vulnerability if a token is intercepted or stolen. Every time a client
   requests a new short-lived access token, the current refresh token is invalidated and replaced with a newly
   issued refresh token. Once rotated, an old refresh token can never be used again.

3. WHY REPLAY ATTACKS REVOKE EVERY SESSION:
   If an attacker intercepts an old refresh token and attempts to use it after the legitimate client has already
   rotated it (or if the legitimate client attempts to use it after an attacker has stolen and rotated it), our
   system detects that an already-revoked valid token (`is_revoked == True`) is being presented. This is direct
   evidence of token reuse and potential session compromise. To protect the user's account, the system immediately
   revokes all active refresh tokens for that account, forcing a clean re-authentication across all devices.
   IMPORTANT DISTINCTION: An entirely random or unknown token string simply raises `RefreshTokenNotFoundError`
   without triggering account-wide revocation. This prevents denial-of-service (DoS) attacks where malicious actors
   could otherwise log out users by submitting random token strings.

4. WHY TRANSACTIONS ARE MANDATORY FOR ROTATION:
   Rotating a refresh token involves two database modifications: revoking the old token hash and inserting the new
   token hash. If these steps were executed without atomic transaction guarantees, server crashes or database errors
   could leave the database in an inconsistent state (e.g., old token revoked but new token missing, causing accidental
   user lockout; or both old and new tokens active, violating single-use rotation guarantees). Executing both updates
   within a single SQLAlchemy transaction ensures all-or-nothing atomicity.

5. WHY REFRESH TOKENS ARE LONGER LIVED THAN ACCESS TOKENS:
   Access tokens (JWTs) are stateless and verified locally without database queries, making them fast but impossible
   to revoke individually before expiration. Therefore, access tokens are given short lifespans (e.g., 15 minutes) to
   limit damage if compromised. Refresh tokens, conversely, require a database query on every rotation and are stored
   securely as hashes. Their longer lifespan (30 days) provides user convenience (persistent login sessions) while
   maintaining security through rotation, device binding, and instant database revocation.
"""

from __future__ import annotations

import logging
import uuid
from dataclasses import dataclass
from datetime import datetime, timezone, timedelta
from typing import TYPE_CHECKING

from app.exceptions import DatabaseOperationError, RepositoryError
from app.models import RefreshToken
from app.models.base import RevocationReason
from app.repositories import RefreshTokenRepository, DeviceRepository
from app.security import (
    generate_refresh_token,
    hash_refresh_token,
    REFRESH_TOKEN_EXPIRE_DAYS,
)
from app.services.exceptions import (
    ServiceError,
    RefreshTokenServiceError,
    RefreshTokenNotFoundError,
    RefreshTokenExpiredError,
    RefreshTokenRevokedError,
    RefreshTokenReplayError,
    DeviceRevokedError,
)

if TYPE_CHECKING:
    pass

logger = logging.getLogger(__name__)


@dataclass(frozen=True)
class RefreshTokenResult:
    """Typed domain result returned when a new refresh token is issued."""
    token: str
    expires_at: datetime
    device_guid: str
    account_id: uuid.UUID


@dataclass(frozen=True)
class RefreshRotationResult:
    """Typed domain result returned upon successful refresh token rotation."""
    new_token: str
    expires_at: datetime
    device_guid: str
    account_id: uuid.UUID


@dataclass(frozen=True)
class RefreshTokenInfo:
    """Typed domain metadata representing a verified refresh token session."""
    token_id: uuid.UUID
    account_id: uuid.UUID
    device_guid: str
    expires_at: datetime
    created_at: datetime
    is_revoked: bool


class RefreshTokenService:
    """
    Core domain service managing Refresh Token Rotation (RTR), session lifecycle,
    device binding, and replay attack detection.
    """

    def __init__(self, repo: RefreshTokenRepository, device_repo: DeviceRepository) -> None:
        self.repo = repo
        self.device_repo = device_repo

    async def _get_and_validate_token(self, plaintext_token: str, *, for_update: bool = False) -> RefreshToken:
        """
        Validate token existence, expiration, and check for replay attack evidence.
        If for_update=True, acquires row-level exclusive lock to prevent concurrent rotation races.

        Replay Attack Invariant:
        - If the token hash does not exist in the database, it is unknown/unrecognized.
          We raise `RefreshTokenNotFoundError` WITHOUT revoking account sessions.
        - If the token hash exists AND `is_revoked == True`, it was previously valid but revoked.
          This is direct evidence of reuse (replay attack). We immediately revoke all account
          sessions and raise `RefreshTokenReplayError`.
        """
        try:
            token_hash = hash_refresh_token(plaintext_token)
        except (TypeError, ValueError) as exc:
            raise RefreshTokenNotFoundError("Invalid refresh token format") from exc

        try:
            entity = await self.repo.get_by_hash(token_hash, for_update=for_update)
        except RepositoryError as exc:
            raise RefreshTokenServiceError("Database error querying refresh token") from exc

        if entity is None:
            # Entirely random or unknown token -> simple failure, NO mass logout
            raise RefreshTokenNotFoundError("Refresh token not found or unrecognized")

        if entity.is_revoked:
            if entity.revoked_reason == RevocationReason.DEVICE_REMOVED:
                raise DeviceRevokedError(
                    "Device was removed by the user.",
                    account_id=entity.account_id,
                    device_guid=entity.device_guid,
                )
            
            # Replay detection: reuse of a legitimately issued token that was previously revoked!
            logger.warning("Replay detected! Revoking all sessions for account.")
            try:
                await self.repo.revoke_all_for_account(entity.account_id)
            except RepositoryError as exc:
                raise RefreshTokenServiceError("Database error during replay mass revocation") from exc
            raise RefreshTokenReplayError(
                "Replay attack detected: reuse of revoked refresh token. All sessions for this account have been revoked.",
                account_id=entity.account_id,
                device_guid=entity.device_guid,
            )

        # Defense-in-depth: check if device is still active
        try:
            device = await self.device_repo.get_by_guid(entity.device_guid)
            if device is not None and not device.is_active:
                raise DeviceRevokedError(
                    "Device is deactivated.",
                    account_id=entity.account_id,
                    device_guid=entity.device_guid,
                )
        except RepositoryError as exc:
            raise RefreshTokenServiceError("Database error checking device status") from exc

        # Defensive timezone normalization: DateTime(timezone=True) should always return
        # tz-aware datetimes, but guard against driver-layer inconsistencies.
        expires_at = entity.expires_at
        if expires_at.tzinfo is None:
            expires_at = expires_at.replace(tzinfo=timezone.utc)
        if expires_at < datetime.now(timezone.utc):
            raise RefreshTokenExpiredError(
                "Refresh token has expired",
                account_id=entity.account_id,
                device_guid=entity.device_guid,
            )

        return entity

    async def issue_refresh_token(self, account_id: uuid.UUID, device_guid: str) -> RefreshTokenResult:
        """
        Issue a new 256-bit CSPRNG refresh token bound to an Account ID and Device GUID.
        Stores only the SHA-256 digest in the database.
        """
        plaintext_token = generate_refresh_token()
        token_hash = hash_refresh_token(plaintext_token)
        expires_at = datetime.now(timezone.utc) + timedelta(days=REFRESH_TOKEN_EXPIRE_DAYS)

        try:
            await self.repo.create(
                account_id=account_id,
                device_guid=device_guid,
                token_hash=token_hash,
                expires_at=expires_at,
            )
        except RepositoryError as exc:
            raise RefreshTokenServiceError("Failed to issue refresh token in database") from exc

        logger.info("Refresh token issued")
        return RefreshTokenResult(
            token=plaintext_token,
            expires_at=expires_at,
            device_guid=device_guid,
            account_id=account_id,
        )

    async def verify_refresh_token(self, plaintext_token: str) -> RefreshTokenInfo:
        """
        Verify a plaintext refresh token, ensuring it exists, is active, and is not expired.
        Returns typed domain metadata without leaking database session state.
        """
        entity = await self._get_and_validate_token(plaintext_token)
        return RefreshTokenInfo(
            token_id=entity.id,
            account_id=entity.account_id,
            device_guid=entity.device_guid,
            expires_at=entity.expires_at,
            created_at=entity.created_at,
            is_revoked=entity.is_revoked,
        )

    async def rotate_refresh_token(self, plaintext_token: str) -> RefreshRotationResult:
        """
        Perform transactional Refresh Token Rotation (RTR).
        Validates the old token (with row locking), marks it revoked, issues a new token bound to the same device,
        and commits both updates in a single atomic database transaction.
        """
        entity = await self._get_and_validate_token(plaintext_token, for_update=True)

        new_plaintext = generate_refresh_token()
        new_hash = hash_refresh_token(new_plaintext)
        new_expires_at = datetime.now(timezone.utc) + timedelta(days=REFRESH_TOKEN_EXPIRE_DAYS)

        try:
            # Step 1: Insert new token entity bound to exact same device_guid within open transaction (commit=False)
            new_entity = RefreshToken(
                account_id=entity.account_id,
                device_guid=entity.device_guid,  # Strict device binding preservation
                token_hash=new_hash,
                expires_at=new_expires_at,
            )
            await self.repo.create(new_entity, commit=False)

            # Step 2: Revoke old token hash within open transaction (commit=False)
            await self.repo.revoke(entity.token_hash, commit=False)

            # Step 3: Commit both operations atomically in one transaction
            await self.repo.session.commit()
            await self.repo.session.refresh(new_entity)
        except Exception as exc:
            await self.repo.session.rollback()
            if isinstance(exc, (ServiceError, RepositoryError)):
                raise
            raise RefreshTokenServiceError("Database error during atomic refresh token rotation") from exc

        logger.info("Refresh token rotated")
        return RefreshRotationResult(
            new_token=new_plaintext,
            expires_at=new_expires_at,
            device_guid=entity.device_guid,
            account_id=entity.account_id,
        )

    async def revoke_refresh_token(self, plaintext_token: str) -> bool:
        """
        Revoke a single refresh token by marking its database record as revoked.
        Returns True if revoked, False if the token was not found or already revoked.
        """
        try:
            token_hash = hash_refresh_token(plaintext_token)
        except (TypeError, ValueError):
            return False

        try:
            revoked = await self.repo.revoke(token_hash)
        except RepositoryError as exc:
            raise RefreshTokenServiceError("Database error revoking refresh token") from exc

        if revoked:
            logger.info("Refresh token revoked")
        return revoked

    async def revoke_all_for_account(self, account_id: uuid.UUID) -> int:
        """
        Revoke all active refresh tokens for an account.
        Returns the count of newly revoked sessions.
        """
        try:
            count = await self.repo.revoke_all_for_account(account_id)
        except RepositoryError as exc:
            raise RefreshTokenServiceError("Database error revoking all sessions for account") from exc

        if count > 0:
            logger.info("All sessions revoked")
        return count

    async def revoke_all_for_device(self, account_id: uuid.UUID, device_guid: str, reason: str = RevocationReason.DEVICE_REMOVED) -> int:
        """
        Revoke all active refresh tokens for a specific device.
        """
        try:
            count = await self.repo.revoke_all_for_device(account_id, device_guid, reason)
        except RepositoryError as exc:
            raise RefreshTokenServiceError("Database error revoking sessions for device") from exc

        if count > 0:
            logger.info(f"All sessions revoked for device {device_guid}")
        return count
