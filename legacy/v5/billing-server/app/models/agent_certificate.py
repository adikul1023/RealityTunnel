"""
agent_certificate.py - Model for node certificates distributed via /configure.
"""
from __future__ import annotations

import uuid
from datetime import datetime
from typing import TYPE_CHECKING
from sqlalchemy import String, Integer, DateTime, text, Uuid, ForeignKey, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database import Base
from app.models.base import TimestampMixin

if TYPE_CHECKING:
    from app.models.agent_node import AgentNode


class AgentCertificate(Base, TimestampMixin):
    """
    AgentCertificate table.
    Stores the TLS certificates generated by nodes and distributed by the billing server.
    Rotations follow a two-phase commit: pending -> active -> retired.
    """
    __tablename__ = "agent_certificates"

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        server_default=text("gen_random_uuid()"),
    )
    node_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("agent_nodes.id", ondelete="CASCADE"), index=True, nullable=False)
    fingerprint: Mapped[str] = mapped_column(String(255), index=True, nullable=False)
    common_name: Mapped[str | None] = mapped_column(String(255), nullable=True)
    algorithm: Mapped[str | None] = mapped_column(String(255), nullable=True)
    expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    rotation_version: Mapped[int] = mapped_column(Integer, nullable=False, default=1)
    
    # Status can be 'pending', 'active', 'retired'
    status: Mapped[str] = mapped_column(String(32), nullable=False, default="pending")
    
    # Encrypted PFX data
    crypto_key_version: Mapped[int] = mapped_column(Integer, nullable=False)
    crypto_nonce: Mapped[str] = mapped_column(String(255), nullable=False)
    crypto_tag: Mapped[str] = mapped_column(String(255), nullable=False)
    encrypted_pfx: Mapped[str] = mapped_column(Text, nullable=False)

    node: Mapped["AgentNode"] = relationship("AgentNode", back_populates="certificates")
